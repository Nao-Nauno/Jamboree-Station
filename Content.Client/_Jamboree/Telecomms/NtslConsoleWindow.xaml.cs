using Content.Shared._Jamboree.Telecomms;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Jamboree.Telecomms;

[GenerateTypedNameReferences]
public sealed partial class NtslConsoleWindow : DefaultWindow
{
    private const int NoServerId = -1;

    public event Action<NetEntity>? OnServerSelected;
    public event Action<string>? OnUpload;
    public event Action? OnClear;
    public event Action<bool>? OnEnabledChanged;
    public event Action? OnRefresh;

    private readonly List<NetEntity> _servers = new();
    private NetEntity? _shownServer;
    private string _shownCode = string.Empty;

    public NtslConsoleWindow()
    {
        RobustXamlLoader.Load(this);

        CodeEdit.Placeholder = new Rope.Leaf(Loc.GetString("ntsl-console-window-placeholder"));

        ServerSelector.OnItemSelected += args =>
        {
            ServerSelector.SelectId(args.Id);
            if (args.Id >= 0 && args.Id < _servers.Count)
                OnServerSelected?.Invoke(_servers[args.Id]);
        };

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        UploadButton.OnPressed += _ => OnUpload?.Invoke(Rope.Collapse(CodeEdit.TextRope));
        ClearButton.OnPressed += _ => OnClear?.Invoke();
        EnabledCheckBox.OnToggled += args => OnEnabledChanged?.Invoke(args.Pressed);
    }

    public void UpdateState(NtslConsoleBoundUserInterfaceState state)
    {
        _servers.Clear();
        ServerSelector.Clear();
        ServerSelector.AddItem(Loc.GetString("ntsl-console-window-choose-server"), NoServerId);
        for (var i = 0; i < state.Servers.Count; i++)
        {
            _servers.Add(state.Servers[i].Server);
            ServerSelector.AddItem(state.Servers[i].Label, i);
        }

        var selectedIndex = state.Selected is { } selected ? _servers.IndexOf(selected) : -1;
        ServerSelector.SelectId(selectedIndex >= 0 ? selectedIndex : NoServerId);

        NoServerLabel.Visible = selectedIndex < 0;
        ServerPanel.Visible = selectedIndex >= 0;

        if (state.Selected != _shownServer || state.Code != _shownCode)
        {
            CodeEdit.TextRope = new Rope.Leaf(state.Code);
            _shownServer = state.Selected;
            _shownCode = state.Code;
        }

        EnabledCheckBox.Pressed = state.Enabled;
        OutputLabel.SetMessage(FormattedMessage.FromUnformatted(state.Output ?? string.Empty));

        var log = state.Log.Count == 0
            ? Loc.GetString("ntsl-console-window-log-empty")
            : string.Join("\n", state.Log);
        LogLabel.SetMessage(FormattedMessage.FromUnformatted(log));
    }
}
